#!/usr/bin/env python3
"""Reference metadata validator for JSONL, JSON, and CSV knowledge records.

This is a standalone companion to the Knowledge Base Ingestion & Update
Technical Specification. It is not wired into the repository's live ingest
pipeline. It uses only the Python standard library.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from datetime import date, datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

REQUIRED = {
    "schema_version", "source_id", "source_type", "domain", "title",
    "content", "updated_at", "language", "product_tags", "category",
    "status", "access_level",
}
ALLOWED_SOURCE_TYPES = {
    "web_page", "blog", "faq", "product", "service", "career",
    "case_study", "policy", "document",
}
ALLOWED_STATUSES = {"active", "draft", "archived", "deleted"}
ALLOWED_ACCESS = {"public", "internal"}
ALLOWED_DOMAINS = {
    "xicteksystems.com", "www.xicteksystems.com",
    "hisabdo.app", "www.hisabdo.app",
}
ALLOWED_TAGS = {
    "hisabdo", "expense-management", "digital-khata", "portfolio",
    "career-services", "custom-software", "mobile-apps",
    "cloud-solutions", "ui-ux",
}
TAG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SOURCE_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{2,127}$")
OPTIONAL_FIELDS = {
    "canonical_url", "published_at", "ingested_at", "content_hash",
    "parser_version", "chunking_version", "source_owner",
}
ALLOWED_FIELDS = REQUIRED | OPTIONAL_FIELDS


class DuplicateKeyError(ValueError):
    pass


def _unique_object(pairs):
    obj = {}
    for key, value in pairs:
        if key in obj:
            raise DuplicateKeyError(f"duplicate JSON key: {key}")
        obj[key] = value
    return obj


def parse_date(value, field, errors, required=False):
    if value is None or value == "":
        if required:
            errors.append(f"{field}: required date is missing")
        return None
    if not isinstance(value, str) or not DATE_RE.fullmatch(value):
        errors.append(f"{field}: expected strict YYYY-MM-DD")
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        errors.append(f"{field}: invalid calendar date")
        return None


def validate_url(url, declared_domain, errors):
    if not url:
        return
    if not isinstance(url, str) or url != url.strip() or any(ch.isspace() for ch in url):
        errors.append("canonical_url: must be a trimmed URL without whitespace")
        return
    try:
        parts = urlsplit(url)
        host = (parts.hostname or "").lower()
        _ = parts.port  # force malformed-port validation
    except ValueError:
        errors.append("canonical_url: malformed URL or port")
        return
    if parts.scheme.lower() != "https":
        errors.append("canonical_url: HTTPS is required")
    if not parts.netloc or not host:
        errors.append("canonical_url: absolute URL with hostname is required")
    if parts.username is not None or parts.password is not None:
        errors.append("canonical_url: embedded credentials are prohibited")
    if parts.fragment:
        errors.append("canonical_url: fragments are prohibited")
    if host not in ALLOWED_DOMAINS:
        errors.append(f"canonical_url: host '{host}' is not allow-listed")
    if declared_domain and host != declared_domain:
        errors.append("canonical_url: hostname does not match declared domain")
    if parts.scheme.lower() == "https" and host in ALLOWED_DOMAINS:
        # Canonical output can be generated by the caller from this normalized value.
        normalized = urlunsplit(("https", host, parts.path or "/", parts.query, ""))
        return normalized
    return None


def validate_record(record, line_label):
    errors = []
    if not isinstance(record, dict):
        return [f"{line_label}: each record must be a JSON object"]

    missing = sorted(k for k in REQUIRED if k not in record or record[k] is None or record[k] == "")
    if missing:
        errors.append(f"{line_label}: missing required fields: {', '.join(missing)}")
    unknown = sorted(set(record) - ALLOWED_FIELDS)
    if unknown:
        errors.append(f"{line_label}: unsupported fields: {', '.join(unknown)}")

    def string_field(name, max_len=None):
        value = record.get(name)
        if value is not None:
            if not isinstance(value, str) or not value.strip():
                errors.append(f"{line_label}: {name} must be a non-empty string")
            elif value != value.strip():
                errors.append(f"{line_label}: {name} must not contain surrounding whitespace")
            elif max_len and len(value) > max_len:
                errors.append(f"{line_label}: {name} exceeds {max_len} characters")

    string_field("schema_version", 20)
    string_field("source_id", 128)
    if record.get("source_id") and isinstance(record["source_id"], str):
        if not SOURCE_ID_RE.fullmatch(record["source_id"]):
            errors.append(f"{line_label}: source_id has invalid characters or length")
    string_field("title", 300)
    string_field("content")
    string_field("domain", 253)
    string_field("language", 35)
    string_field("category", 80)

    if record.get("schema_version") not in (None, "1.0"):
        errors.append(f"{line_label}: unsupported schema_version (expected 1.0)")
    if record.get("source_type") not in (None, *ALLOWED_SOURCE_TYPES):
        errors.append(f"{line_label}: unsupported source_type")
    if record.get("status") not in (None, *ALLOWED_STATUSES):
        errors.append(f"{line_label}: status must be active/draft/archived/deleted")
    if record.get("access_level") not in (None, *ALLOWED_ACCESS):
        errors.append(f"{line_label}: access_level must be public or internal")

    domain = record.get("domain")
    if domain is not None and domain not in ALLOWED_DOMAINS:
        errors.append(f"{line_label}: domain is not allow-listed")

    canonical = record.get("canonical_url")
    if record.get("source_type") in {"web_page", "blog", "faq", "product", "service", "career", "case_study", "policy"} and not canonical:
        errors.append(f"{line_label}: canonical_url is required for web-backed source_type")
    normalized_url = validate_url(canonical, domain, errors) if canonical else None

    published = parse_date(record.get("published_at"), "published_at", errors)
    updated = parse_date(record.get("updated_at"), "updated_at", errors, required=True)
    if published and updated and published > updated:
        errors.append(f"{line_label}: published_at cannot be later than updated_at")

    ingested = record.get("ingested_at")
    if ingested:
        try:
            parsed = datetime.fromisoformat(ingested.replace("Z", "+00:00"))
            if parsed.tzinfo is None or parsed.utcoffset() != timezone.utc.utcoffset(parsed):
                errors.append(f"{line_label}: ingested_at must be an ISO 8601 UTC timestamp ending in Z or +00:00")
        except (TypeError, ValueError, AttributeError):
            errors.append(f"{line_label}: ingested_at must be a valid ISO 8601 UTC timestamp")

    tags = record.get("product_tags")
    if tags is not None:
        if not isinstance(tags, list):
            errors.append(f"{line_label}: product_tags must be a JSON array")
        else:
            if len(tags) != len(set(t for t in tags if isinstance(t, str))):
                errors.append(f"{line_label}: product_tags must not contain duplicates")
            for tag in tags:
                if not isinstance(tag, str) or not TAG_RE.fullmatch(tag):
                    errors.append(f"{line_label}: invalid product tag {tag!r}; use lowercase kebab-case")
                elif tag not in ALLOWED_TAGS:
                    errors.append(f"{line_label}: unapproved product tag {tag!r}")

    if record.get("content") is not None and isinstance(record["content"], str):
        if not record["content"].strip():
            errors.append(f"{line_label}: content must not be empty")

    return errors


def load_jsonl(path):
    records, errors = [], []
    with path.open("r", encoding="utf-8-sig") as f:
        for number, raw in enumerate(f, 1):
            if not raw.strip():
                continue
            try:
                records.append(json.loads(raw, object_pairs_hook=_unique_object))
            except (json.JSONDecodeError, DuplicateKeyError) as exc:
                errors.append(f"line {number}: JSON parse error: {exc}")
    return records, errors


def load_json(path):
    try:
        value = json.loads(path.read_text(encoding="utf-8-sig"), object_pairs_hook=_unique_object)
    except (json.JSONDecodeError, DuplicateKeyError) as exc:
        return [], [f"JSON parse error: {exc}"]
    if isinstance(value, dict):
        return [value], []
    if isinstance(value, list):
        return value, []
    return [], ["JSON top level must be an object or an array of objects"]


def load_csv(path):
    records, errors = [], []
    with path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            return [], ["CSV must contain a header row"]
        if len(reader.fieldnames) != len(set(reader.fieldnames)):
            return [], ["CSV contains duplicate column headers"]
        for row_number, row in enumerate(reader, 2):
            if None in row:
                errors.append(f"row {row_number}: unexpected extra columns")
                continue
            record = {k: (v.strip() if isinstance(v, str) and v.strip() else None) for k, v in row.items()}
            if isinstance(record.get("product_tags"), str):
                try:
                    record["product_tags"] = json.loads(record["product_tags"])
                except json.JSONDecodeError:
                    errors.append(f"row {row_number}: product_tags must be JSON array syntax")
            records.append(record)
    return records, errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("file", type=Path, help="Input .jsonl, .json, or .csv file")
    args = parser.parse_args()
    suffix = args.file.suffix.lower()
    loaders = {".jsonl": load_jsonl, ".ndjson": load_jsonl, ".json": load_json, ".csv": load_csv}
    if suffix not in loaders:
        print("ERROR: supported formats are .jsonl, .ndjson, .json, .csv", file=sys.stderr)
        return 2

    records, parse_errors = loaders[suffix](args.file)
    errors = list(parse_errors)
    for idx, record in enumerate(records, 1):
        errors.extend(validate_record(record, f"record {idx}"))

    if errors:
        print(f"VALIDATION FAILED: {len(errors)} issue(s) across {len(records)} parsed record(s)")
        for error in errors:
            print(f"- {error}")
        return 1
    print(f"VALIDATION PASSED: {len(records)} record(s) in {args.file}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
