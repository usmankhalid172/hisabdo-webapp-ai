bad_refs = []
for case in cases:
    for ref in case["supporting_source_records"]:
        record_id = ref.split("#", 1)[1]
        if record_id not in known:
            bad_refs.append((case["id"], ref))

loaded = json.loads((ROOT / "data" / "department3_evaluation_v1.json").read_text(encoding="utf-8"))
